"""Catalog and validate independent figure files without assembling a deck."""
from pathlib import Path
import hashlib,json,xml.etree.ElementTree as ET
import fitz
from PIL import Image,ImageDraw
HERE=Path(__file__).resolve().parent
SLIDES=HERE.parent


def main():
    items=[]
    for filename,section in [('quantitative_figures.json','Saved-data evidence'),
                             ('method_figures.json','Methods, interpretation and proposed work')]:
        obj=json.loads((HERE/filename).read_text())
        for x in obj['figures']:
            items.append({**x,'section':section,'folder':str(HERE)})
    obj=json.loads((SLIDES/'framework-figures/figures.json').read_text())
    for x in obj['figures']:
        items.append({**x,'section':'Agentic framework','kind':'framework diagram',
                      'files':x['outputs'],'folder':str(HERE)})
    for name,folder,stem,exts,caption in [
      ('AMP versus ADP mechanism comparison',HERE.name,'amp_adp_comparison',['png','svg','pdf','tex'],
       'Expanded LaTeX comparison of carboxyl activation and relevant enzyme families.'),
      ('ADP-forming PuuA geometry',HERE.name,'PuuA_ADP_attack_geometry',['png','svg','pdf'],
       'Unchanged saved predicted coordinates; two Mg ions are modeled, not experimentally established stoichiometry.'),
      ('AMP-forming AS9 geometry',HERE.name,'AS9_attack_geometry',['png'],
       'Existing one-pose AS9 illustration; retained as the matching AMP-forming reference.'),
    ]:
        files=[f'{stem}.{e}' for e in exts]
        items.append({'name':name,'section':'Mechanistic chemistry and structures','kind':'table / coordinate illustration',
                      'caption':caption,'folder':str(SLIDES/folder),'files':files})
    order=['AMP versus ADP mechanism comparison','AMP-forming AS9 geometry','ADP-forming PuuA geometry',
           'modeling_setup_audit','structural_proxy_search_inventory','assay_key_candidates_and_controls',
           'all_explored_proxy_comparison','current_metric_shortlist_recovery',
           'activation_vs_aminolysis_readouts','complete_mutant_geometry_tradeoffs',
           'adaptive_decision_loop','shared_evidence_handoff','proposed_framework_evaluation',
           'proposed_multistate_motif_constraints']
    assert {x['name'] for x in items}==set(order)
    items.sort(key=lambda x:order.index(x['name']))
    checks=[];outliers=[];text_overlaps=[];pdf_overlap_checks=0
    for i,item in enumerate(items,1):
        item['index']=i;item['absolute_files']=[]
        for f in item['files']:
            p=Path(item['folder'])/f;assert p.is_file(),p
            item['absolute_files'].append(str(p))
            if p.suffix=='.svg':ET.parse(p)
            elif p.suffix=='.png':
                with Image.open(p) as im:im.verify()
            elif p.suffix=='.pdf':
                with fitz.open(p) as d:
                    assert len(d)==1,(p,len(d))
                    r=d[0].rect;rendered_lines=[];pdf_overlap_checks+=1
                    for b in d[0].get_text('dict')['blocks']:
                        for line in b.get('lines',[]):
                            line_text=''.join(s['text'] for s in line['spans']).strip()
                            if line_text:rendered_lines.append((line_text,fitz.Rect(line['bbox'])))
                            for s in line['spans']:
                                box=fitz.Rect(s['bbox'])
                                if box.x0 < -8 or box.y0 < -8 or box.x1 > r.width+8 or box.y1 > r.height+8:
                                    outliers.append({'file':str(p),'text':s['text'],'bbox':list(box)})
                    for j,(text_a,box_a) in enumerate(rendered_lines):
                        for text_b,box_b in rendered_lines[j+1:]:
                            overlap=box_a&box_b
                            if overlap.is_empty or overlap.width<=1.5 or overlap.height<=1.5:continue
                            ratio=overlap.get_area()/min(box_a.get_area(),box_b.get_area())
                            if ratio>.09:text_overlaps.append({'file':str(p),'first':text_a,
                                'second':text_b,'smaller_box_overlap_fraction':ratio})
            checks.append({'path':str(p),'bytes':p.stat().st_size,
                           'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
    lines=['CANDIDACY BACKUP VISUALIZATION INDEX',
      'Standalone assets for the user to assemble; no deck is generated by this catalog.',
      f'Root: {SLIDES}',f'Indexed figures: {len(items)}',
      'Focused collection: 14 figures. Supplementary diagnostics and reference material are archived.',
      'Archive location and restoration information: cleanup_manifest.json.',
      '', 'INTERPRETATION',
      'Quantitative plots use saved measurements and predictions. Model samples are not biological replicates.',
      'The current weighted angle A is separate from older tuned Gaussian scores.',
      'The homolog panel has been repeatedly inspected; none of these plots establishes independent validation.',
      'Proposed experiments, success criteria and design investigations are labeled as proposals.',
      'The 2023 workbook has calibration/repeat notes, but no verified mapping to the 2025 activity panel.',
      'PuuA contains two modeled Mg ions; this does not establish native metal stoichiometry.',
      '', 'FIGURES']
    previous=None
    for x in items:
        if x['section']!=previous:
            lines.extend(['',x['section'].upper()]);previous=x['section']
        lines.extend(['',f'{x["index"]:02d}. {x.get("title",x["name"])}',f'Type: {x["kind"]}',x['caption']])
        lines.extend(x['absolute_files'])
    lines.extend(['','EVIDENCE STILL REQUIRED FOR NEW RESULTS',
      'Confirmed product identity and panel-specific calibration / detection limits.',
      'A documented biological-versus-technical repeat structure and expression normalization.',
      'Independent reaction benchmarks and prospective mutant / de novo activity measurements.',
      'Validated dynamics or chemical-barrier results for the proposed follow-up hypotheses.',
      'These gaps are shown as validation requirements; they are not filled with invented data.'])
    (HERE/'FIGURE_INDEX.txt').write_text('\n'.join(lines)+'\n')
    (HERE/'figure_catalog.json').write_text(json.dumps({'count':len(items),'figures':items},indent=2)+'\n')
    (HERE/'asset_validation.json').write_text(json.dumps({'figures':len(items),'checked_files':len(checks),
      'single_page_pdfs':True,'valid_pngs_and_svgs':True,'text_bbox_outliers':outliers,
      'pdf_text_overlap_checks':pdf_overlap_checks,'text_overlaps':text_overlaps,
      'files':checks},indent=2)+'\n')
    preview=HERE/'previews';preview.mkdir(exist_ok=True)
    for start in range(0,len(items),12):
        canvas=Image.new('RGB',(1920,4*440),'#E7E7E7');draw=ImageDraw.Draw(canvas)
        for j,item in enumerate(items[start:start+12]):
            png=next((Path(p) for p in item['absolute_files'] if p.endswith('.png')),None)
            if png is None:continue
            with Image.open(png) as im:
                im=im.convert('RGB');im.thumbnail((625,395));x=j%3*640;y=j//3*440
                canvas.paste(im,(x+(630-im.width)//2,y+30))
                draw.text((x+8,y+8),f'{item["index"]:02d} {item["name"][:57]}',fill='black')
        canvas.save(preview/f'overview-{start//12+1:02d}.png')
    print(json.dumps({'figures':len(items),'checked_files':len(checks),'text_bbox_outliers':len(outliers),
                     'text_overlaps':len(text_overlaps)}))
    if outliers:print(json.dumps(outliers[:8],indent=2))
    if text_overlaps:raise ValueError(json.dumps(text_overlaps[:12],indent=2))


if __name__=='__main__':main()
