#!/usr/bin/env python3
"""Run the PRE-REGISTERED tests. Nothing here may be chosen after seeing the data.

See PREREGISTRATION.md. Implemented exactly as written there:

  T1/T2   within-acid rank tests (actives occupy the top ranks by A), exact p
  T5      per-panel continuous Spearman among DETECTED enzymes
  TP1     pooled trend: within-panel Spearman combined by Stouffer z, weights sqrt(n-3),
          one-tailed positive  (amendment 3)
  TP2     pooled separation: detected-vs-LOD AUROC with a PANEL-STRATIFIED permutation null
          (labels permuted within panel only, 20 000 draws)  (amendment 3)
  TP3     TP1/TP2 restricted to n_gated > 0 -- SECONDARY, explicitly not a rescue (amendment 2)

  Reported alongside, unconditionally (amendments 1 and 3):
    corr(A, n_gated) over all ensembles   -- is A reporting docking rather than catalysis?
    ANL vs NIS fold comparison            -- a trend that dies within fold family is an artifact

Writes analysis/PREREGISTERED_RESULTS.md and prints the same.
"""
import csv, math, pathlib, random, sys

CAMP = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(CAMP))
from plot_panels import SOURCES, REACTION, load, rank_test, spearman  # noqa: E402

FOLD = {"DdaG": "ANL", "SfaB": "ANL",
        "AsbA": "NIS", "AsbB": "NIS", "AcsA": "NIS", "DesD": "NIS"}
PANEL_ACID = {}
for _n, (_p, _panels, _o) in SOURCES.items():
    PANEL_ACID.update(_panels)
N_PERM = 20000
random.seed(20261021)      # fixed so the permutation null is reproducible


def ndtr(z):
    return 0.5 * math.erfc(-z / math.sqrt(2))


def auroc(scores, labels):
    """P(score of a positive > score of a negative), ties at 0.5."""
    pos = [s for s, l in zip(scores, labels) if l]
    neg = [s for s, l in zip(scores, labels) if not l]
    if not pos or not neg:
        return None
    tot = sum((1.0 if a > b else 0.5 if a == b else 0.0) for a in pos for b in neg)
    return tot / (len(pos) * len(neg))


def stratified_auroc(cells):
    """Pooled AUROC over (panel, A, detected) triples -- pooled, panel used only by the null."""
    return auroc([c[1] for c in cells], [c[2] for c in cells])


def main():
    sc = {}
    f = CAMP / "analysis/step1_scores.csv"
    if not f.exists():
        sys.exit("no step-1 scores yet")
    for r in csv.DictReader(f.open()):
        if int(r["n_mg"]) == 1:
            sc[(r["enzyme"], r["acid_code"])] = r

    labels = {}
    for _n, (path, _panels, _o) in SOURCES.items():
        if path.exists():
            labels.update(load(path))

    out = ["# Pre-registered results", "",
           "Generated by `run_tests.py`. Tests and thresholds fixed in `PREREGISTRATION.md` "
           "before folding; amendments 1-3 were all written before the relevant panels completed.",
           ""]

    # ---------- per-panel (T1/T2/T5) ------------------------------------------------------
    out += ["## Per-panel tests", "",
            "| panel | reaction | acid | detected/total | actives top-ranked by A | exact p | "
            "rho(A, activity) | p |", "|---|---|---|---|---|---|---|---|"]
    per_panel = []
    for panel in sorted(PANEL_ACID):
        lab = labels.get(panel)
        acid = PANEL_ACID[panel]
        if not lab:
            continue
        have = [e for e in lab if (e, acid) in sc]
        if len(have) < len(lab):
            out.append(f"| {panel} | {REACTION.get(panel,'')} | {acid} | — | pending "
                       f"({len(have)}/{len(lab)} folded) | — | — | — |")
            continue
        A = {e: float(sc[(e, acid)]["A_deg"]) for e in have}
        det = [e for e in have if not lab[e]["below_LOD"]]
        perfect, p_rank = rank_test(A, det)
        rho, p_rho = (spearman([A[e] for e in det], [lab[e]["value"] for e in det])
                      if len(det) >= 3 else (None, None))
        per_panel.append((panel, rho, p_rho, len(det)))
        out.append(f"| {panel} | {REACTION.get(panel,'')} | {acid} | {len(det)}/{len(have)} | "
                   f"{'no contrast' if perfect is None else ('YES' if perfect else 'NO')} | "
                   f"{'—' if p_rank is None else f'{p_rank:.3f}'} | "
                   f"{'—' if rho is None else f'{rho:+.2f}'} | "
                   f"{'—' if p_rho is None else f'{p_rho:.3f}'} |")

    # ---------- TP1 pooled trend ----------------------------------------------------------
    usable = [(p, r, n) for p, r, pr, n in per_panel if r is not None and n >= 4]
    out += ["", "## TP1 — pooled trend (Stouffer-combined within-panel Spearman)", ""]
    if len(usable) < 2:
        out.append(f"Not evaluable yet: {len(usable)} panel(s) with >=4 detected enzymes.")
        z_comb = None
    else:
        zs, ws = [], []
        for p, r, n in usable:
            r = max(-0.999999, min(0.999999, r))
            zs.append(0.5 * math.log((1 + r) / (1 - r)) * math.sqrt(max(n - 3, 1)))
            ws.append(math.sqrt(max(n - 3, 1)))
        z_comb = sum(zs) / math.sqrt(sum(w * w for w in ws))
        p_one = 1 - ndtr(z_comb)
        out += [f"Panels combined: {len(usable)} — " +
                ", ".join(f"{p} rho={r:+.2f} (n={n})" for p, r, n in usable), "",
                f"**Stouffer z = {z_comb:+.3f}, one-tailed p = {p_one:.4f}**", "",
                ("Positive trend detected." if p_one < 0.05 else
                 "**No detectable trend at this n.** Per the pre-registration this is reported as "
                 "no detectable trend, NOT as a refutation of A: with 4-6 enzymes per stratum the "
                 "pooled design retains only modest power, and a null is consistent with a real "
                 "but small effect.")]

    # ---------- TP2 pooled separation -----------------------------------------------------
    cells = []
    for panel in sorted(PANEL_ACID):
        lab, acid = labels.get(panel), PANEL_ACID[panel]
        if not lab:
            continue
        have = [e for e in lab if (e, acid) in sc]
        if len(have) < len(lab):
            continue
        for e in have:
            cells.append((panel, float(sc[(e, acid)]["A_deg"]), not lab[e]["below_LOD"]))
    out += ["", "## TP2 — pooled detected-vs-LOD separation, panel-stratified null", ""]
    obs = stratified_auroc(cells) if cells else None
    if obs is None:
        out.append("Not evaluable: no panel with both detected and below-LOD cells yet.")
    else:
        by_panel = {}
        for pan, a, d in cells:
            by_panel.setdefault(pan, []).append((a, d))
        ge = 0
        for _ in range(N_PERM):
            perm = []
            for pan, rows in by_panel.items():
                labs = [d for _a, d in rows]
                random.shuffle(labs)
                perm += [(a, l) for (a, _d), l in zip(rows, labs)]
            v = auroc([a for a, _l in perm], [l for _a, l in perm])
            if v is not None and v >= obs:
                ge += 1
        p_perm = (ge + 1) / (N_PERM + 1)
        npos = sum(1 for _p, _a, d in cells if d)
        out += [f"Cells pooled: {len(cells)} ({npos} detected, {len(cells)-npos} below LOD) "
                f"across {len(by_panel)} panels", "",
                f"**AUROC = {obs:.3f}, panel-stratified permutation p = {p_perm:.4f}** "
                f"({N_PERM} draws)", "",
                "Labels were permuted WITHIN panel only: detection rates differ enormously between "
                "panels (2A is 6/6, 5C is 1/4), so an unstratified null would be badly "
                "anticonservative."]

    # ---------- mandatory companions ------------------------------------------------------
    allr = list(sc.values())
    xs = [int(r["n_gated"]) for r in allr]
    ys = [float(r["A_deg"]) for r in allr]
    rho_g, p_g = spearman(xs, ys) if len(xs) >= 3 else (None, None)
    out += ["", "## Reported unconditionally (amendments 1 and 3)", "",
            f"**rho(A, n_gated) = {rho_g:+.3f}, p = {p_g:.4g}** over {len(xs)} ensembles.",
            "", ("A is significantly coupled to docking quality, so it is partly reporting "
                 "WHETHER THE LIGAND DOCKED rather than how well the enzyme catalyses — the same "
                 "artifact that invalidated the hydrolase campaign."
                 if (p_g is not None and p_g < 0.05) else
                 "No significant coupling to docking quality at this n.")]

    anl = [float(r["A_deg"]) for r in allr if FOLD.get(r["enzyme"]) == "ANL"]
    nis = [float(r["A_deg"]) for r in allr if FOLD.get(r["enzyme"]) == "NIS"]
    if anl and nis:
        ma, mn = sum(anl) / len(anl), sum(nis) / len(nis)
        pooled = [(x, 0) for x in anl] + [(x, 1) for x in nis]
        a_fold = auroc([x for x, _ in pooled], [l for _, l in pooled])
        out += ["", f"**Fold family:** mean A — ANL {ma:.1f} (n={len(anl)}) vs "
                f"NIS {mn:.1f} (n={len(nis)}); AUROC(NIS > ANL) = {a_fold:.3f}.",
                "", "A separates FOLD FAMILIES. Any apparent activity trend that disappears "
                "within fold family is a fold artifact, not a catalytic signal."]

    txt = "\n".join(out) + "\n"
    (CAMP / "analysis/PREREGISTERED_RESULTS.md").write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
