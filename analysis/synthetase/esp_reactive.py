#!/usr/bin/env python3
"""ESP-at-reactive-atom electrostatics proxy (KG shortlist; PMID 35655887).

Electrostatic potential at the reactive atom generated by the surrounding PROTEIN
partial charges:  ESP = sum_i q_i / r_i  over protein atoms within 15 A of the
reactive atom (ligand/HET atoms EXCLUDED). Uniform dielectric eps=1 and the
1/(4*pi*eps0) prefactor are dropped -> arbitrary units, but RANKING is invariant
to any uniform dielectric, so this is fine for surfacing (documented).

Two species / two reactive atoms:
  step-1 (adenylation)  : ATP P-alpha  (ligand atom 'PA')      -> esp_pa
  step-2 (intermediate) : acyl-AMP carbonyl C (the electrophile -> esp_carbonyl
        the amine attacks), identified as the ligand C whose O-neighbour is the
        ester O bridging to the phosphorus (distinguishes it from the free distal
        carboxylate C).

Charges: real Amber (ff14SB) partial charges via pdb2pqr30, run ONCE per enzyme
per step on model_0. pdb2pqr adds hydrogens; each H charge is COLLAPSED onto its
nearest heavy atom (bond <1.3 A) so per-residue net charge is preserved exactly
without needing H coordinates in every pose. The resulting heavy-atom charge map
(keyed by chain,resid,atomname) is then applied to all 50 poses using each pose's
own heavy-atom coordinates. Protonation states (HID/HIE, termini) are whatever
pdb2pqr assigns from model_0; adequate for a ranking proxy.

Output: exp_data/amide_synthetase/analysis/esp_reactive.csv
        (id, esp_pa, esp_pa_std, esp_carbonyl, esp_carbonyl_std)

Usage: python analysis/synthetase/esp_reactive.py
"""
import os, sys, glob, csv, math, subprocess, tempfile
os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("MKL_NUM_THREADS", "1")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
from multiprocessing import Pool
import numpy as np

ROOT = "/nfs/lambda_stor_01/homes/rzhu/Enzyme_agent"
P1 = f"{ROOT}/exp_data/amide_synthetase/boltz2/step1_1mg/results"
P2 = f"{ROOT}/exp_data/amide_synthetase/boltz2/step2_1mg/results"
OUT = f"{ROOT}/exp_data/amide_synthetase/analysis/esp_reactive.csv"
RCUT = 15.0      # A, protein atoms within this of reactive atom contribute
PDB2PQR = "pdb2pqr30"


def pred1(e): return f"{P1}/{e}/boltz_results_step1_{e}/predictions/step1_{e}"
def pred2(e): return f"{P2}/{e}/boltz_results_step2_{e}/predictions/step2_{e}"


def is_H(name):
    return name.lstrip("0123456789")[:1] == "H"


def parse_pdb_protein(path):
    """protein heavy atoms -> list of (chain, resid, atomname, np.xyz)."""
    out = []
    with open(path) as f:
        for L in f:
            if L[:4] != "ATOM":
                continue
            name = L[12:16].strip()
            if is_H(name):
                continue
            ch = L[21]; resid = L[22:26].strip()
            xyz = np.array([float(L[30:38]), float(L[38:46]), float(L[46:54])])
            out.append((ch, resid, name, xyz))
    return out


def parse_pdb_het(path):
    """HET atoms -> list of (name, element, np.xyz)."""
    out = []
    with open(path) as f:
        for L in f:
            if L[:6] != "HETATM":
                continue
            name = L[12:16].strip()
            el = L[76:78].strip() or name[0]
            xyz = np.array([float(L[30:38]), float(L[38:46]), float(L[46:54])])
            out.append((name, el.upper(), xyz))
    return out


def build_charge_map(model0_pdb):
    """Run pdb2pqr on model0; collapse H charges onto heavy atoms.
    Returns {(chain,resid,atomname): charge} for heavy atoms, plus net charge."""
    with tempfile.NamedTemporaryFile(suffix=".pqr", delete=False) as tf:
        pqr = tf.name
    try:
        r = subprocess.run(
            [PDB2PQR, "--ff=AMBER", "--noopt", "--keep-chain", model0_pdb, pqr],
            capture_output=True, text=True, timeout=300)
        if not os.path.isfile(pqr) or os.path.getsize(pqr) == 0:
            return None, None
        # parse PQR: ATOM serial name resname chain resid x y z charge radius
        heavy = {}   # (chain,resid,name) -> [charge, xyz]
        hyd = []     # (chain,resid, charge, xyz)
        with open(pqr) as f:
            for L in f:
                if L[:4] != "ATOM":
                    continue
                p = L.split()
                # robust from the right: radius, charge, z, y, x
                try:
                    q = float(p[-2]); x = float(p[-5]); y = float(p[-4]); z = float(p[-3])
                except (ValueError, IndexError):
                    continue
                name = p[2]; ch = p[4]; resid = p[5]
                xyz = np.array([x, y, z])
                if is_H(name):
                    hyd.append((ch, resid, q, xyz))
                else:
                    heavy[(ch, resid, name)] = [q, xyz]
        # collapse each H onto nearest heavy atom in same (chain,resid) within 1.3 A
        by_res = {}
        for (ch, resid, name), (q, xyz) in heavy.items():
            by_res.setdefault((ch, resid), []).append((name, xyz))
        for ch, resid, q, xyz in hyd:
            cand = by_res.get((ch, resid))
            if not cand:
                continue
            nm, _ = min(cand, key=lambda t: np.linalg.norm(t[1] - xyz))
            heavy[(ch, resid, nm)][0] += q
        cmap = {k: v[0] for k, v in heavy.items()}
        net = sum(cmap.values())
        return cmap, net
    finally:
        try: os.remove(pqr)
        except OSError: pass


def esp_at(reactive_xyz, protein, cmap):
    """sum q_i / r_i over protein heavy atoms within RCUT of reactive atom."""
    s = 0.0
    for ch, resid, name, xyz in protein:
        q = cmap.get((ch, resid, name))
        if q is None:
            continue
        r = np.linalg.norm(xyz - reactive_xyz)
        if r < RCUT and r > 1e-3:
            s += q / r
    return s


def step1_reactive(het):
    for name, el, xyz in het:
        if el == "P" and name == "PA":
            return xyz
    return None


def step2_reactive(het):
    """acyl-AMP carbonyl C: ligand C whose O-neighbour bridges to a P (ester O)."""
    Ps = [xyz for name, el, xyz in het if el == "P"]
    Cs = [(name, xyz) for name, el, xyz in het if el == "C"]
    Os = [(name, xyz) for name, el, xyz in het if el == "O"]
    if not Ps or not Cs:
        return None
    best = None
    for cname, cxyz in Cs:
        onb = [oxyz for oname, oxyz in Os if np.linalg.norm(oxyz - cxyz) < 1.7]
        if len(onb) < 2:
            continue
        # does one O neighbour bridge to a phosphorus (ester O)?
        bridges = any(np.linalg.norm(o - p) < 1.8 for o in onb for p in Ps)
        if bridges:
            # prefer the C closest to a P (the acyl centre, not a phosphodiester)
            dmin = min(np.linalg.norm(cxyz - p) for p in Ps)
            if best is None or dmin < best[0]:
                best = (dmin, cxyz)
    return best[1] if best else None


def enzyme(e):
    res = {"id": e, "esp_pa": None, "esp_pa_std": None,
           "esp_carbonyl": None, "esp_carbonyl_std": None}
    # --- step 1 ---
    pdbs = sorted(glob.glob(f"{pred1(e)}/*model_*.pdb"))
    if pdbs:
        cmap, net = build_charge_map(pdbs[0])
        if cmap:
            vals = []
            for p in pdbs:
                ra = step1_reactive(parse_pdb_het(p))
                if ra is None:
                    continue
                vals.append(esp_at(ra, parse_pdb_protein(p), cmap))
            if vals:
                res["esp_pa"] = round(float(np.mean(vals)), 4)
                res["esp_pa_std"] = round(float(np.std(vals)), 4)
    # --- step 2 ---
    pdbs = sorted(glob.glob(f"{pred2(e)}/*model_*.pdb"))
    if pdbs:
        cmap, net = build_charge_map(pdbs[0])
        if cmap:
            vals = []
            for p in pdbs:
                ra = step2_reactive(parse_pdb_het(p))
                if ra is None:
                    continue
                vals.append(esp_at(ra, parse_pdb_protein(p), cmap))
            if vals:
                res["esp_carbonyl"] = round(float(np.mean(vals)), 4)
                res["esp_carbonyl_std"] = round(float(np.std(vals)), 4)
    return res


def main():
    enz = sorted([os.path.basename(d) for d in glob.glob(f"{P1}/*") if os.path.isdir(d)])
    with Pool(8) as pool:
        rows = pool.map(enzyme, enz)
    cols = ["id", "esp_pa", "esp_pa_std", "esp_carbonyl", "esp_carbonyl_std"]
    with open(OUT, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(rows)
    n1 = sum(1 for r in rows if r["esp_pa"] is not None)
    n2 = sum(1 for r in rows if r["esp_carbonyl"] is not None)
    print(f"wrote {OUT}  ({len(rows)} enzymes; step1 esp_pa n={n1}, step2 esp_carbonyl n={n2})")


if __name__ == "__main__":
    main()
